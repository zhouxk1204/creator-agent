def parse_srt(path):
    with open(path, "r", encoding="utf-8-sig") as f:
        raw = f.read()
    entries = []
    blocks = raw.strip().split("\n\n")
    for block in blocks:
        lines = block.strip().split("\n")
        if len(lines) >= 3:
            idx = int(lines[0])
            time_range = lines[1]
            text = "\n".join(lines[2:])
            entries.append({"idx": idx, "time": time_range, "text": text})
    return entries

def time_to_ms(t):
    h, m, s = t.replace(",", ".").split(":")
    return int(h) * 3600000 + int(m) * 60000 + int(float(s) * 1000)

def ms_to_srt(ms):
    h = ms // 3600000; ms %= 3600000
    m = ms // 60000; ms %= 60000
    s = ms // 1000; ms %= 1000
    return f"{h:02d}:{m:02d}:{s:02d},{ms:03d}"

def parse_time_range(s):
    p = s.split(" --> ")
    return time_to_ms(p[0].strip()), time_to_ms(p[1].strip())

