def main():
    entries = parse_srt(SRC)
    jp = {e["idx"]: e for e in entries}
    output = []
    for gi, (start, end, cn_text) in enumerate(GROUPS, 1):
        start_ms = None; end_ms = None
        for i in range(start, end + 1):
            s, e = parse_time_range(jp[i]["time"])
            if start_ms is None or s < start_ms: start_ms = s
            if end_ms is None or e > end_ms: end_ms = e
        time_line = f"{ms_to_srt(start_ms)} --> {ms_to_srt(end_ms)}"
        output.append(f"{gi}\n{time_line}\n{cn_text}")
    with open(DST, "w", encoding="utf-8-sig") as f:
        f.write("\n\n".join(output) + "\n")
    print(f"Done! {len(GROUPS)} groups written.")

if __name__ == "__main__":
    main()
